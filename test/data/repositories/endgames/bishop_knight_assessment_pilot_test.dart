  test(
    'reserved short line covers every legal defense and ends in real mate',
    () async {
      final exercise = (await _lesson()).exercise(_exerciseId)!;
      final root = GameRules.fromFen(exercise.fen)!;
      var position = root;
      final history = <String>[];
      final actualLine = <String>[];
      for (final turn in exercise.line) {
        actualLine.add(turn.accept.first);
        if (turn.reply != null) actualLine.add(turn.reply!);
      }
      expect(actualLine, _verifiedLine);
      expect(exercise.line, hasLength(3));
      for (var i = 0; i < actualLine.length; i++) {
        expect(
          GameRules.endOf(
            position,
            repetitions: GameRules.repetitionsOf(root, history),
          ),
          isNull,
          reason: 'No move is played after a prior terminal.',
        );
        if (position.turn == Side.black) {
          // The reserve proves all defenses of this short plan only.
          expect(_legalUcis(position), {actualLine[i]});
        }
        final played = GameRules.play(position, Move.parse(actualLine[i])!);
        expect(played, isNotNull);
        position = played!.position;
        history.add(actualLine[i]);
        expect(position.fen, _verifiedSuccessors[i]);
        expect(position.halfmoves, lessThan(GameRules.fiftyMovesInPlies));
        expect(GameRules.repetitionsOf(root, history), 1);
        expect(position.isCheckmate, i == actualLine.length - 1);
      }
      final end = GameRules.endOf(
        position,
        repetitions: GameRules.repetitionsOf(root, history),
      );
      expect(end?.reason, GameEndReason.checkmate);
      expect(end?.winner, Side.white);
      expect(position.turn, Side.black);
      expect(_legalUcis(position), isEmpty);
    },
  );

  test(
    'all reserved winning root choices stay listed without implying mate',
    () async {
      final exercise = (await _lesson()).exercise(_exerciseId)!;
      final root = GameRules.fromFen(exercise.fen)!;
      final accept = exercise.line.first.accept;
      expect(accept, hasLength(21));
      expect(_legalUcis(root), {...accept, 'c4d5'});
      for (final uci in accept) {
        final played = GameRules.play(root, Move.parse(uci)!);
        expect(played, isNotNull);
        expect(played!.position.isCheckmate, isFalse);
        expect(GameRules.endOf(played.position, repetitions: 1), isNull);
      }
      // This is the reserve's single drawing root move, not an illegal move.
      final draw = GameRules.play(root, Move.parse('c4d5')!);
      expect(draw, isNotNull);
      expect(draw!.position.isStalemate, isTrue);
      expect(
        GameRules.endOf(draw.position, repetitions: 1)?.reason,
        GameEndReason.stalemate,
      );
      expect(accept, isNot(contains('c4d5')));
      // Nonterminal is not a WDL proof. Long alternative trees remain unproved
      // here; production requires the strict judge and its real proof provider.
    },
  );

  test(
    'assessment root is absent from the actual teaching and practice',
    () async {
      final lesson = await _lesson();
      final exercise = lesson.exercise(_exerciseId)!;
      final script = LessonScript.fromJson(
        await _readJson(lesson.lesson.parts.single.script!),
      );
      final exposed = <String>{
        _positionKey(lesson.practice.fen),
        for (final key in lesson.keyPositions) _positionKey(key.fen),
        for (final stage in script.stages)
          for (final example in stage.examples) ...[
            _positionKey(example.fen),
            for (final step in [...example.entry, ...example.line])
              _positionKey(step.fen),
          ],
      };
      expect(exposed, isNot(contains(_positionKey(exercise.fen))));
      // Exact exposure check only. D4/translation novelty is in the frozen
      // reserve snapshot, not certified again by this test.
    },
  );

  test(
    'PT and EN resolve neutral statement and hint in production namespace',
    () async {
      for (final language in ['pt', 'en']) {
        final raw = await _readJson(
          'assets/lessons/$language/endgames/$_lessonId.json',
        );
        final prefixed = AssetEndgameLessonRepository.prefixed(_lessonId, raw);
        for (final suffix in ['', '.hint']) {
          final text = prefixed['$_lessonId.ex.$_exerciseId$suffix'] as String;
          expect(text.trim(), isNotEmpty);
          expect(RegExp(r'[a-h][1-8]').hasMatch(text), isFalse);
          for (final move in _verifiedLine) {
            expect(text, isNot(contains(move)));
          }
        }
      }
    },
  );
