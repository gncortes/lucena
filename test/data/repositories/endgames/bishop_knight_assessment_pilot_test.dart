const _descriptorPath = 'assets/lessons/endgames/$_lessonId.json';

// Restricted assessment fixture: copied from the already verified reserve.
// No new engine verdicts or continuations are generated by these tests.
// Original proof SHA-256:
// db09e02c6903cf2320f6abb7706eeb86855ac1c56744b8835e05bc35b4daff20
const _verifiedRoot = '8/k1K5/8/8/1NB5/8/8/8 w - - 0 1';
const _verifiedLine = ['c4a6', 'a7a8', 'a6b7', 'a8a7', 'b4c6'];
const _verifiedSuccessors = [
  '8/k1K5/B7/8/1N6/8/8/8 b - - 1 1',
  'k7/2K5/B7/8/1N6/8/8/8 w - - 2 2',
  'k7/1BK5/8/8/1N6/8/8/8 b - - 3 2',
  '8/kBK5/8/8/1N6/8/8/8 w - - 4 3',
  '8/kBK5/2N5/8/8/8/8/8 b - - 5 3',
