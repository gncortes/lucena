Future<Map<String, dynamic>> _readJson(String path) async =>
    jsonDecode(await io.File(path).readAsString()) as Map<String, dynamic>;

Future<EndgameLesson> _lesson() async =>
    AssetEndgameLessonRepository.parseLesson(await _readJson(_descriptorPath));

Set<String> _legalUcis(Position position) => {
  for (final entry in GameRules.legalMoves(position).entries)
    for (final to in entry.value) NormalMove(from: entry.key, to: to).uci,
};

String _positionKey(String fen) => fen.split(' ').take(4).join(' ');

class _CheckoutAssets extends AssetService {
  @override
  Future<String> loadString(String path) => io.File(path).readAsString();

  @override
  Future<Uint8List> loadBytes(String path) => io.File(path).readAsBytes();
}

class _SyntheticConflictAssets extends _CheckoutAssets {
  _SyntheticConflictAssets(this.overrides);
  final Map<String, Uint8List> overrides;

  @override
  Future<String> loadString(String path) async => overrides.containsKey(path)
      ? utf8.decode(overrides[path]!)
      : super.loadString(path);

  @override
  Future<Uint8List> loadBytes(String path) async =>
      overrides[path] ?? await super.loadBytes(path);
}

ExerciseJudge _productionJudge() => ExerciseJudge(
  AssetExerciseProofCatalogRepository(
    _CheckoutAssets(),
    path: AssetExerciseProofCatalogRepository.defaultPath,
  ),
);

void main() {
  test(
    'real replay adapter matches the frozen reserved route at every prefix',
    () {
      const adapter = AssessmentExecutionAdapter();
      for (var ply = 0; ply <= _verifiedLine.length; ply++) {
        final execution = adapter.replay(
          initialFen: _verifiedRoot,
          student: Side.white,
          played: _verifiedLine.take(ply).toList(),
          expectedFen: ply == 0 ? _verifiedRoot : _verifiedSuccessors[ply - 1],
        );
        expect(execution.historyVerified, isTrue);
        expect(execution.visitedSnapshots, hasLength(ply + 1));
        expect(execution.studentMate, ply == _verifiedLine.length);
        expect(execution.terminal, ply == _verifiedLine.length);
      }
    },
  );

  TestWidgetsFlutterBinding.ensureInitialized();

  test('synthetic contradictory overlap stays indeterminate', () async {
    const indexPath = AssetExerciseProofCatalogRepository.defaultPath;
    final manifest = await _readJson(indexPath);
    final entry = (manifest['entries'] as List)[1] as Map<String, dynamic>;
    final envelope = await _readJson(entry['path'] as String);
    final response =
        jsonDecode(envelope['raw'] as String) as Map<String, dynamic>;
    // Deliberately false transport data, only for a negative rejection test.
    // No winning claim is taken from this synthetic fixture.
    expect(response['category'], 'loss');
    response['category'] = 'win';
    response['dtz'] = (response['dtz'] as int).abs();
    response['precise_dtz'] = (response['precise_dtz'] as int).abs();
    final raw = jsonEncode(response);
    final digest = sha256.convert(utf8.encode(raw)).toString();
    envelope['raw'] = raw;
    envelope['rawSha256'] = digest;
    entry['rawSha256'] = digest;
    final catalog = AssetExerciseProofCatalogRepository(
      _SyntheticConflictAssets({
        indexPath: Uint8List.fromList(utf8.encode(jsonEncode(manifest))),
        entry['path'] as String: Uint8List.fromList(
          utf8.encode(jsonEncode(envelope)),
        ),
      }),
      path: indexPath,
    );
    final result = await catalog.lookup(entry['queryFen'] as String);
    expect(result, isA<ExerciseIndeterminate>());
    expect((result as ExerciseIndeterminate).reason, 'conflictingProof');
  });

  test(
    'packaged real proofs certify every reserved winning root choice',
    () async {
      final exercise = (await _lesson()).exercise(_exerciseId)!;
      final root = GameRules.fromFen(exercise.fen)!;
      final judge = _productionJudge();
      for (final uci in exercise.line.first.accept) {
        final child = GameRules.play(root, Move.parse(uci)!)!.position;
        final result = await judge.evaluate(
          ExerciseJudgeRequest(
            initialFen: root.fen,
            fen: child.fen,
            student: root.turn,
            played: [uci],
            historyComplete: true,
          ),
        );
        expect(result, isA<ExerciseKnown>(), reason: 'Recorded root coverage');
        final known = result as ExerciseKnown;
        expect(known.wdl, Wdl.win);
        expect(known.perspective, root.turn);
        expect(known.sourceSha256, isNotEmpty);
      }
    },
  );

  test('native execution scores only at mate using packaged proofs', () async {
    final lesson = await _lesson();
    final exercise = lesson.exercise(_exerciseId)!;
    final progress = FakeEndgameProgressRepository();
    final opponent = FakeOpponentRepository();
    final cubit = ExerciseCubit(
      lessons: FakeEndgameLessonRepository(
        trail: EndgameTrail(
          modules: [
            EndgameModule(id: 'mates', lessons: [lesson]),
          ],
        ),
      ),
      progress: progress,
      characters: FakeCharacterRepository(),
      now: FakeNow(DateTime.utc(2026, 10, 18)),
      exerciseJudge: _productionJudge(),
      opponent: opponent,
      replyDelay: Duration.zero,
    );
    addTearDown(cubit.close);
    await cubit.load(_lessonId, _exerciseId, 'pt');
    for (var i = 0; i < exercise.line.length; i++) {
      await cubit.play(Move.parse(exercise.line[i].accept.first)!);
      expect(cubit.state.technicalFailure, isNull);
      expect(cubit.state.mistakes, 0);
      if (i < exercise.line.length - 1) {
        expect(cubit.state.phase, isNot(ExercisePhase.done));
        expect(progress.saved.of(_lessonId).stars, isEmpty);
      }
    }
    expect(
      opponent.requests,
      isEmpty,
    ); // Registered replies, not a fake engine verdict.
    expect(cubit.state.played, _verifiedLine);
    expect(cubit.state.phase, ExercisePhase.done);
    expect(cubit.state.earned, 1);
    expect(progress.saved.of(_lessonId).stars, {_exerciseId: 1});
    expect(progress.saved.of(_lessonId).exercise, isNull);
    // The review intentionally displays an earlier decision. Verify the
    // terminal from the complete persisted game, not the review cursor.
    var terminal = GameRules.fromFen(exercise.fen)!;
    for (final uci in cubit.state.played) {
      terminal = GameRules.play(terminal, Move.parse(uci)!)!.position;
    }
    expect(terminal.fen, _verifiedSuccessors.last);
    expect(terminal.isCheckmate, isTrue);
    expect(GameRules.endOf(terminal)?.winner, Side.white);
  });

